-- Studyspace server-side schema for Supabase Postgres.
-- Safe to run more than once. Passwords are stored as salted hashes by the app;
-- this schema does not create Supabase Auth users or contain any credentials.

CREATE TABLE IF NOT EXISTS public.studyspace_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  is_owner SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.studyspace_sessions (
  token_hash TEXT PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES public.studyspace_accounts(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS studyspace_sessions_account_idx
  ON public.studyspace_sessions(account_id);

CREATE UNIQUE INDEX IF NOT EXISTS studyspace_single_owner_idx
  ON public.studyspace_accounts (is_owner) WHERE is_owner = 1;

CREATE TABLE IF NOT EXISTS public.studyspace_user_databases (
  account_id BIGINT PRIMARY KEY REFERENCES public.studyspace_accounts(id) ON DELETE CASCADE,
  db_data BYTEA NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.studyspace_migrations (
  name TEXT PRIMARY KEY,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.studyspace_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studyspace_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studyspace_user_databases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studyspace_migrations ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.studyspace_accounts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.studyspace_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.studyspace_user_databases FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.studyspace_migrations FROM PUBLIC, anon, authenticated;
